"""CLI, scheduler and delivery: the operational glue."""

from dataclasses import replace

import httpx

from trendsignal.cli import main
from trendsignal.delivery import send_telegram, to_plain_text
from trendsignal.scheduler import build_scheduler


def test_cli_init_top_and_sources_run_against_an_empty_database(settings, capsys):
    assert main(["init"]) == 0
    assert main(["top", "--limit", "3"]) == 0
    assert main(["sources"]) == 0
    out = capsys.readouterr().out
    assert "database ready" in out and "openai_news" in out


def test_cli_digest_without_stories_uses_the_template(settings, capsys):
    assert main(["digest", "--no-llm", "--no-deliver"]) == 0
    assert "generated by template" in capsys.readouterr().out


def test_scheduler_runs_the_ranker_and_the_daily_forecast_refresh_by_default(ctx):
    assert {job.id for job in build_scheduler(ctx).get_jobs()} == {"pipeline", "forecast_refresh", "retention"}


def test_scheduler_adds_briefs_when_enabled(ctx):
    with_briefs = replace(ctx, settings=replace(ctx.settings, write_briefs=True))
    assert {job.id for job in build_scheduler(with_briefs).get_jobs()} == {
        "pipeline", "forecast_refresh", "retention", "daily_digest", "weekly_digest"}


def test_plain_text_drops_citations_and_markdown():
    text = to_plain_text("# Brief\n\n1. **Title** [S12]\n   [Read the source](https://x.example/a) [S12]\n")
    assert text == "Brief\n\n1. Title\n   Read the source: https://x.example/a"


def test_telegram_is_skipped_when_not_configured(settings):
    assert send_telegram(settings, "# Brief") == (False, "Telegram not configured")


def test_telegram_sends_in_chunks_and_reports_http_errors(settings):
    configured = replace(settings, telegram_bot_token="bot-token", telegram_chat_id="42")
    sent = []

    def ok(request):
        sent.append(request)
        return httpx.Response(200, json={"ok": True})

    long_brief = "\n\n".join(f"Paragraph {i} " + "x" * 900 for i in range(10))
    assert send_telegram(configured, long_brief, httpx.Client(transport=httpx.MockTransport(ok))) == (True, None)
    assert len(sent) >= 3

    failing = httpx.Client(transport=httpx.MockTransport(lambda request: httpx.Response(401)))
    assert send_telegram(configured, "# Brief", failing) == (False, "Telegram returned HTTP 401")
